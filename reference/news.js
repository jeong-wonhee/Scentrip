function newsPlaces(m) {
  return (m.placeIds || []).map((id) => {
    if (!PLACE_DB[id] && !newsWarned[m.id + id]) { newsWarned[m.id + id] = 1; console.warn(`[Scentrip] 소식 '${m.id}' 의 장소 '${id}' 를 찾지 못해 뺐어요.`); }
    return PLACE_DB[id];
  }).filter(Boolean);
}
